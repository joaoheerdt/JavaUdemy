package VetoresAndList.exercicio03.entities;

public class Guests {
    private String guest;
    private String email;

    public Guests(String guest, String email) {
        this.guest = guest;
        this.email = email;
    }

    public String getGuest() {
        return guest;
    }

    public String getEmail() {
        return email;

    }
}
